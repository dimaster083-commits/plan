/* ЧТО СЕГОДНЯ. Сводка обязана быть честной ровно там, где честность
   неудобна: когда добрать надо больше, чем осталось дней. Поэтому почти у
   каждой проверки рядом стоит «наивный» счёт — тот, который считает по
   календарным дням или рисует бодрый прогресс, — и мы смотрим, что сводка
   с ним расходится. Проверка, которая согласна и с наивным счётом, и с
   честным, ничего не меряет.

   Журнал засеваем сами: S.rec и S.start. Экран не обязателен — функции
   объявлены глобально, поэтому числа меряются напрямую. Две проверки на
   саму отрисовку мягкие: карточка вешается в HOOK.prog, и если фишку ещё
   не подключили, они честно об этом скажут, но набор не уронят. */
const fs = require('fs');
const path = require('path');
const { chromium } = require('playwright-core');
const { LAUNCH, APP } = require('../env');

let fails = 0;
const ok = (n, d) => console.log('  ✓ ' + n + (d ? '   → ' + d : ''));
const bad = (n, d) => { fails++; console.log('  ✗ ' + n + (d ? '   → ' + d : '')); };
const chk = (c, n, d) => c ? ok(n, d) : bad(n, d);
const мягко = (c, n, d) => c ? ok(n, d) : console.log('  ✓ ' + n + '   → пропущено: ' + d);

// даты считаем локально, без UTC: иначе вечером день уезжает на вчера
const dISO = d => d.getFullYear() + '-' + String(d.getMonth() + 1).padStart(2, '0') +
  '-' + String(d.getDate()).padStart(2, '0');
const сдвиг = (ds, n) => { const d = new Date(ds + 'T12:00:00'); d.setDate(d.getDate() + n); return dISO(d); };

// засев журнала: стартовая дата и список дат закрытых тренировок
const засеять = (p, старт, даты) => p.evaluate(o => {
  S.rec = {}; S.map = {};
  S.start = o.старт;
  o.даты.forEach(ds => { S.rec[ds] = { log: {}, sp: {}, wo: 1 }; });
  save();
  return { старт: S.start, всего: Object.keys(S.rec).length };
}, { старт: старт, даты: даты });

const сводка = (p, ds) => p.evaluate(d => segodnyaSvodka(d), ds);
const разметка = (p, ds) => p.evaluate(d => segodnyaHtml(d), ds);

(async () => {
  const b = await chromium.launch(LAUNCH);

  for (const skin of ['sl', 'ber']) {
    console.log('\n===== ' + skin + ' =====');
    const p = await (await b.newContext({ viewport: { width: 320, height: 720 } })).newPage();
    const errs = []; p.on('pageerror', e => errs.push(e.message));
    await p.goto(APP); await p.waitForTimeout(1300);

    await p.evaluate(s => {
      S.setup = 1; const su = document.getElementById('setup');
      if (su) su.classList.remove('on');
      applyTheme(s); S.sound = 0;
    }, skin);

    const есть = await p.evaluate(() => typeof segodnyaSvodka === 'function' &&
      typeof segodnyaHtml === 'function' && typeof segodnyaCard === 'function');
    chk(есть, '1. функции сводки объявлены глобально', 'segodnyaSvodka / segodnyaHtml / segodnyaCard');
    if (!есть) { await p.context().close(); continue; }

    const пн = await p.evaluate(() => mondayOf(today()));
    const Д = n => сдвиг(пн, n);          // 0 Пн · 1 Вт · 3 Чт · 5 Сб · 6 Вс

    /* ---------- 1. понедельник, ноль из четырёх ---------- */
    await засеять(p, пн, []);
    const пон = await сводка(p, Д(0));
    chk(пон && пон.закрыто === 0 && пон.осталось === 3 && пон.норма === 3,
      '2. в понедельник закрыто 0, добрать 3', пон && (пон.закрыто + '/' + пон.норма));
    chk(пон.доступно === 4 && пон.днейВпереди === 7,
      '3. впереди вся неделя: 7 дней, 4 тренировочных',
      'дней ' + пон.днейВпереди + ', закрыть можно ' + пон.доступно);
    chk(пон.успеваем === true && пон.вердикт === 'успеваем' &&
      /Успеть ещё можно/.test(пон.вердиктТекст),
      '4. сводка говорит, что успеть ещё можно', пон.вердиктТекст);

    /* ---------- 2. воскресенье, один из четырёх ---------- */
    await засеять(p, пн, [Д(1)]);
    const вс = await сводка(p, Д(6));
    chk(вс.закрыто === 1 && вс.осталось === 2 && вс.доступно === 1 && вс.днейВпереди === 1,
      '5. в воскресенье закрыто 1, добрать 2, а день один',
      'осталось ' + вс.осталось + ', дней ' + вс.доступно);
    chk(вс.успеваем === false && вс.вердикт === 'срыв' &&
      /не засчитается/.test(вс.вердиктТекст),
      '6. сводка честно говорит: неделя уже не засчитается', вс.вердиктТекст);
    chk(/Добрать 2/.test(вс.вердиктПодпись) && /дней осталось 1/.test(вс.вердиктПодпись),
      '7. и называет обе цифры, а не рисует прогресс', вс.вердиктПодпись);

    /* ---------- 3. сторож: календарные дни врут именно в пятницу ---------- */
    /* Пятница по программе — отдых. Календарь обещает три дня впереди,
       закрыть можно только два. Наивный счёт «осталось <= дней впереди»
       здесь говорит «успеваем», честный — «срыв». Если сводка согласится
       с наивным, проверка это увидит. */
    await засеять(p, пн, []);
    const пт = await сводка(p, Д(4));
    const наивноУспеваем = пт.осталось <= пт.днейВпереди;
    chk(пт.днейВпереди === 3 && пт.доступно === 2,
      '8. в пятницу календарь даёт 3 дня, а закрыть можно 2',
      'дней ' + пт.днейВпереди + ', закрыть можно ' + пт.доступно);
    chk(наивноУспеваем === true && пт.успеваем === false && пт.вердикт === 'срыв',
      '9. сторож: наивный счёт по календарю сказал бы «успеваем», сводка — нет',
      'наивно ' + наивноУспеваем + ', честно ' + пт.успеваем);

    /* ---------- 4. норма закрыта ---------- */
    await засеять(p, пн, [Д(1), Д(3), Д(5)]);
    const норма = await сводка(p, Д(6));
    chk(норма.закрыто === 3 && норма.осталось === 0 && норма.успеваем === true &&
      норма.вердикт === 'засчитана' && /засчитана/.test(норма.вердиктТекст),
      '10. норма набрана — неделя засчитана', норма.вердиктТекст);
    chk(!/[Дд]обрать/.test(норма.вердиктПодпись) && !/не засчитается/.test(норма.вердиктПодпись),
      '11. и ничего лишнего не требует', норма.вердиктПодпись);

    /* ---------- 5. день отдыха ---------- */
    const отдых = await сводка(p, Д(0));          // понедельник — отдых по TPL
    const трен = await сводка(p, Д(1));           // вторник — верх тела
    const отдыхHTML = await разметка(p, Д(0));
    const тренHTML = await разметка(p, Д(1));
    chk(отдых.отдых === true && отдых.подходовПлан === 0 && отдых.упражнений === 0,
      '12. понедельник опознан как отдых', 'упражнений ' + отдых.упражнений);
    chk(!/подход/i.test(отдыхHTML) && /подход/i.test(тренHTML),
      '13. в день отдыха про подходы ни слова, а в тренировочный — слово есть',
      'отдых: ' + (/подход/i.test(отдыхHTML) ? 'есть' : 'нет') +
      ', тренировка: ' + (/подход/i.test(тренHTML) ? 'есть' : 'нет'));
    chk(трен.отдых === false && трен.упражнений > 0 && трен.подходовПлан > 0,
      '14. у тренировочного дня есть упражнения и подходы',
      трен.упражнений + ' упр. · ' + трен.подходовПлан + ' подходов');

    /* ---------- 6. подходы берутся из журнала ---------- */
    const подх = await p.evaluate(d => {
      const день = dayOf(d);
      const r = recRW(d);
      r.log[0] = { done: 1, n: день.ex[0].n, s: 4, r: '5', w: 50, vol: 1000 };
      save();
      return { журнал: daySets(d), сводка: segodnyaSvodka(d).подходовЗакрыто };
    }, Д(1));
    chk(подх.сводка === подх.журнал && подх.журнал > 0,
      '15. закрытые подходы берутся из daySets, а не пересчитываются',
      'журнал ' + подх.журнал + ', сводка ' + подх.сводка);

    /* ---------- 7. серия ---------- */
    const полные = [];
    [1, 2, 3].forEach(k => [1, 3, 5, 6].forEach(i => полные.push(сдвиг(пн, -7 * k + i))));
    await засеять(p, сдвиг(пн, -21), полные);
    const сер = await p.evaluate(d => ({ s: segodnyaSvodka(d), st: streak() }), Д(0));
    chk(сер.s.серия === сер.st && сер.st === 3,
      '16. серия недель совпадает со streak()', 'сводка ' + сер.s.серия + ', streak ' + сер.st);
    chk(сер.s.серияПодУгрозой === true && сер.s.доСерии === 4,
      '17. серия оборвётся, если эту неделю не добрать до четырёх',
      'добрать ' + сер.s.доСерии);
    const сер2 = await p.evaluate(o => {
      [o.вт, o.чт, o.сб, o.вс].forEach(ds => { S.rec[ds] = { log: {}, sp: {}, wo: 1 }; });
      save();
      return { s: segodnyaSvodka(o.пн), st: streak() };
    }, { пн: Д(0), вт: Д(1), чт: Д(3), сб: Д(5), вс: Д(6) });
    chk(сер2.s.серия === сер2.st && сер2.st === 4 && сер2.s.серияПодУгрозой === false,
      '18. добрал четыре — серия выросла и угрозы нет',
      'сводка ' + сер2.s.серия + ', streak ' + сер2.st);

    /* ---------- 8. разгрузка ---------- */
    /* Пять зачтённых недель подряд — и текущая становится шестой, разгрузочной. */
    const пять = [];
    for (let k = 5; k >= 1; k--) [1, 3, 5].forEach(i => пять.push(сдвиг(пн, -7 * k + i)));
    await засеять(p, сдвиг(пн, -35), пять);
    const круг = await p.evaluate(o => o.даты.map(d => {
      const s = segodnyaSvodka(d);
      return { н: s.неделя, ц: s.циклН, через: s.разгрузкаЧерез,
        неделяР: s.разгрузкаНеделя, на: s.наРазгрузке };
    }), { даты: [0, 1, 2, 3, 4, 5].map(k => сдвиг(пн, -35 + 7 * k)) });
    const циклы = круг.map(x => x.ц).join(',');
    chk(циклы === '1,2,3,4,5,6', '19. пять зачтённых недель довели цикл до шестой', циклы);
    chk(круг.every(x => x.через === (x.ц === 6 ? 0 : 6 - x.ц)),
      '20. до разгрузки считается верно на каждой неделе цикла',
      круг.map(x => x.ц + '→' + x.через).join(' '));
    chk(круг.every(x => x.через >= 0) && круг.every(x => x.неделяР === 6),
      '21. и ни на одной неделе не уходит в минус',
      'минимум ' + Math.min(...круг.map(x => x.через)));
    const шестая = круг[5];
    const наивно = 5 - шестая.ц;           // ходовая ошибка: 0-based индекс против 1-based недели
    chk(шестая.на === true && шестая.через === 0 && наивно < 0,
      '22. сторож: на самой разгрузке наивная формула даёт минус, сводка — ноль',
      'наивно ' + наивно + ', сводка ' + шестая.через);

    /* ---------- 9. план ещё не начался ---------- */
    await засеять(p, сдвиг(пн, 70), []);
    const ждём = await сводка(p, Д(0));
    const ждёмHTML = await разметка(p, Д(0));
    chk(ждём.ждём === true && ждём.вердикт === 'ждём' && ждём.доСтарта === 70,
      '23. старт в будущем — сводка говорит про ожидание',
      ждём.вердиктТекст + ' · через ' + ждём.доСтарта);
    chk(/Старт/.test(ждём.вердиктПодпись) && !/не засчитается/.test(ждёмHTML) &&
      !/Зачёт/i.test(ждёмHTML) && !/Разгрузка/i.test(ждёмHTML),
      '24. и не врёт про недели: ни зачёта, ни разгрузки, ни срыва', ждём.вердиктПодпись);
    await засеять(p, пн, []);
    const начался = await разметка(p, Д(0));
    chk(/Зачёт/i.test(начался) && /Разгрузка/i.test(начался),
      '25. сторож: когда план начался, зачёт и разгрузка на месте',
      'зачёт ' + /Зачёт/i.test(начался) + ', разгрузка ' + /Разгрузка/i.test(начался));

    /* ---------- 10. отрисовка (мягко) ---------- */
    const нарисовано = await p.evaluate(() => {
      try { tab = 'prog'; render(); } catch (e) { return { есть: false, почему: e.message }; }
      const box = document.getElementById('hookProg');
      const c = box ? box.querySelector('.sgd') : null;
      if (!c) return { есть: false, почему: 'HOOK.prog пуст — фишка не подключена' };
      const r = c.getBoundingClientRect();
      const шире = [...c.querySelectorAll('*')].filter(e => {
        const q = e.getBoundingClientRect();
        return q.right > r.right + 0.6 || q.left < r.left - 0.6;
      }).map(e => e.className || e.tagName);
      return { есть: true, право: Math.round(r.right), шире: шире,
        докСкролл: document.documentElement.scrollWidth,
        докШирина: document.documentElement.clientWidth,
        текст: c.textContent.replace(/\s+/g, ' ').trim().slice(0, 120) };
    });
    мягко(нарисовано.есть, '26. карточка отрисована на вкладке «Прогресс»',
      нарисовано.почему || '');
    if (нарисовано.есть) {
      chk(нарисовано.шире.length === 0 && нарисовано.докСкролл <= нарисовано.докШирина + 1,
        '27. на 320 px ничего не вылезает за края',
        'док ' + нарисовано.докСкролл + '/' + нарисовано.докШирина +
        (нарисовано.шире.length ? ' · ' + нарисовано.шире.join(', ') : ''));
      chk(/Что сегодня/i.test(нарисовано.текст),
        '28. в карточке видна её подпись', нарисовано.текст.slice(0, 60));
    } else {
      мягко(false, '27. на 320 px ничего не вылезает за края', 'карточка не на экране');
      мягко(false, '28. в карточке видна её подпись', 'карточка не на экране');
    }

    /* ---------- 11. цвета и ошибки ---------- */
    const краски = await p.evaluate(() => {
      const c = document.createElement('div');
      c.innerHTML = segodnyaHtml(today());
      document.getElementById('hookProg').appendChild(c);
      const карт = c.querySelector('.sgd');
      const цв = e => getComputedStyle(e).color;
      const r = { текст: цв(карт.querySelector('.sgd-vt')),
        фон: getComputedStyle(карт).backgroundColor,
        метка: цв(карт.querySelector('.sgd-r>span')) };
      c.remove();
      return r;
    });
    chk(краски.текст !== краски.метка && /rgb/.test(краски.текст),
      '29. вердикт и подписи красятся переменными темы',
      'вердикт ' + краски.текст + ', метка ' + краски.метка);

    chk(errs.length === 0, '30. без ошибок в консоли', errs.join(' | ') || 'чисто');
    await p.context().close();
  }

  await b.close();

  /* ---------- 12. стили: своих цветов нет ---------- */
  const css = fs.readFileSync(path.join(__dirname, '..', '..', 'feat', 'segodnya.css'), 'utf8');
  const hex = css.match(/#[0-9a-fA-F]{3,8}\b/g) || [];
  const свои = css.match(/\b(rgb|rgba|hsl|hsla)\s*\(/g) || [];
  console.log('\n===== стили =====');
  chk(hex.length === 0 && свои.length === 0,
    '31. в стилях фишки нет ни своих hex, ни своих rgb', hex.concat(свои).join(', ') || 'чисто');
  const перем = [...new Set((css.match(/var\(--[a-z0-9-]+\)/g) || []))];
  const разрешено = ['--ink', '--ink3', '--ln', '--s2', '--acc', '--warn', '--up-tx', '--down-tx'];
  const чужие = перем.filter(v => !разрешено.includes(v.slice(4, -1)));
  chk(перем.length > 0 && чужие.length === 0,
    '32. взяты только оговорённые переменные', чужие.join(', ') || перем.join(' '));

  console.log('\nпроблем: ' + fails);
  process.exit(fails ? 1 : 0);
})();
