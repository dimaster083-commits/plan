/* =========================================================================
   ЧТО СЕГОДНЯ — короткий честный ответ на «что мне сделать, чтобы не
   сорвать план».

   Одна карточка, по которой принимают решение «иду сегодня или нет».
   Ничего не считает заново: недели берутся из weekCounts/doneThisWeek,
   подходы — из daySets (то есть из журнала), цикл — из planWeek/cycIdx,
   серия — из streak(). Своих формул здесь ровно две, и обе про честность:

   1. Дней впереди и дней, в которые ещё можно закрыть тренировку, — это
      разные числа. В пятницу календарь обещает три дня, а закрыть можно
      только два: пятница сама по программе отдых. Бодрый прогресс на
      календарных днях врал бы ровно в тот момент, когда врать нельзя.

   2. Если добрать надо больше, чем осталось дней, неделя уже не
      засчитается — и сводка говорит это прямо, а не рисует полоску.

   Карточка вешается в реестр HOOK.prog (контейнер #hookProg на вкладке
   «Прогресс»). Регистрация — в самом низу файла, одной строкой.
   ========================================================================= */

/* Сводка одним объектом. Всё, что показывает карточка, считается здесь,
   чтобы разметка не думала, а проверки могли мерить числа без экрана. */
function segodnyaSvodka(ds) {
  if (typeof S !== 'object' || !S || !Array.isArray(S.days) || !S.days.length) return null;

  const день = (typeof ds === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(ds)) ? ds : today();
  const д = at(день);
  if (isNaN(д.getTime())) return null;
  const пн = mondayOf(день);
  if (!пн) return null;

  const wd = (д.getDay() + 6) % 7;                    // Пн=0 … Вс=6
  const днейВпереди = 7 - wd;                         // сегодняшний день считается
  const деньНедели = n => { const c = at(пн); c.setDate(c.getDate() + n); return iso(c); };

  /* ---- план вообще начался? ---- */
  const стартДата = planStart();
  const ждём = !started(день);
  const доСтарта = ждём ? Math.max(0, Math.round((at(стартДата) - д) / 864e5)) : 0;

  /* ---- зачёт недели ---- */
  const закрыто = doneThisWeek(день);
  const норма = WEEK_MIN;
  const осталось = Math.max(0, норма - закрыто);

  /* Сколько дней этой недели ещё можно закрыть. Считаем только те, где
     программа даёт тренировку и где она ещё не закрыта: в отдых зачёт
     не поставишь, а закрытый день уже посчитан в «закрыто». */
  let доступно = 0;
  for (let i = wd; i <= 6; i++) {
    const дт = деньНедели(i);
    if (!дт) continue;
    const дн = dayOf(дт) || {};
    if (!((дн.ex || []).length)) continue;
    if (recOf(дт).wo) continue;
    доступно++;
  }
  const успеваем = осталось === 0 || осталось <= доступно;

  /* ---- сегодняшний день ---- */
  const дн = dayOf(день) || {};
  const упражнений = (дн.ex || []).length;
  const отдых = дн.t === 'rest' || упражнений === 0;
  const подходовПлан = отдых ? 0 : (дн.ex || []).reduce((a, e, j) => {
    const b = num(e.s);
    try { return a + (typeof setsOf === 'function' ? setsOf(день, b, j) : b); }
    catch (_) { return a + b; }
  }, 0);
  const подходовЗакрыто = отдых ? 0 : daySets(день);
  const деньЗакрыт = !!recOf(день).wo;

  /* ---- серия ---- */
  /* streak() засчитывает только полные недели по четыре тренировки —
     значит и порог у серии свой, он не совпадает с WEEK_MIN. */
  const серия = (typeof streak === 'function') ? streak() : 0;
  const полная = 4;
  const доСерии = Math.max(0, полная - закрыто);
  const серияПодУгрозой = !ждём && серия > 0 && доСерии > 0;
  const серияВозможна = доСерии <= доступно;

  /* ---- ближайшая разгрузка ---- */
  const неделя = planWeek(день);
  const циклВсего = CYCLE.length;
  const циклН = cycIdx(день) + 1;                     // 1…6, как видит человек
  let через = -1;
  for (let i = 0; i < циклВсего; i++) {
    if (CYCLE[(циклН - 1 + i) % циклВсего].ph === 'РАЗГРУЗКА') { через = i; break; }
  }
  // по кругу: на самой разгрузке 0, дальше — сколько недель ждать. Минуса тут нет.
  const разгрузкаЕсть = через >= 0;
  const разгрузкаЧерез = разгрузкаЕсть ? через : 0;
  const разгрузкаНеделя = разгрузкаЕсть ? ((циклН - 1 + через) % циклВсего) + 1 : 0;
  const наРазгрузке = разгрузкаЕсть && через === 0;

  /* ---- вердикт ---- */
  let вердикт;
  if (ждём) вердикт = 'ждём';
  else if (осталось === 0) вердикт = 'засчитана';
  else if (осталось > доступно) вердикт = 'срыв';
  else вердикт = 'успеваем';

  const трен = n => plural(n, 'тренировку', 'тренировки', 'тренировок');
  const дня = n => plural(n, 'день', 'дня', 'дней');
  let вердиктТекст = '', вердиктПодпись = '';
  if (вердикт === 'ждём') {
    вердиктТекст = 'План ещё не начался';
    вердиктПодпись = доСтарта === 0
      ? 'Старт сегодня — недели считаются с него'
      : 'Старт ' + (typeof fmt === 'function' ? fmt(стартДата) : стартДата) +
        ', через ' + доСтарта + ' ' + дня(доСтарта);
  } else if (вердикт === 'засчитана') {
    вердиктТекст = 'Неделя засчитана';
    вердиктПодпись = 'Норма ' + норма + ' из 4 закрыта, план идёт дальше';
  } else if (вердикт === 'срыв') {
    вердиктТекст = 'Неделя уже не засчитается';
    вердиктПодпись = 'Добрать ' + осталось + ' ' + трен(осталось) + ', а дней осталось ' +
      доступно + ' — план останется на этой же неделе';
  } else {
    вердиктТекст = 'Успеть ещё можно';
    вердиктПодпись = 'Добрать ' + осталось + ' ' + трен(осталось) + ', впереди ' +
      доступно + ' ' + дня(доступно);
  }

  return {
    дата: день, пн: пн, деньНедели: wd,
    ждём: ждём, стартДата: стартДата, доСтарта: доСтарта,
    неделя: неделя, циклН: циклН, циклВсего: циклВсего,
    закрыто: закрыто, норма: норма, осталось: осталось,
    днейВпереди: днейВпереди, доступно: доступно, успеваем: успеваем,
    вердикт: вердикт, вердиктТекст: вердиктТекст, вердиктПодпись: вердиктПодпись,
    отдых: отдых, деньИмя: дн.n || '', деньПодпись: дн.s || '',
    упражнений: упражнений, подходовПлан: подходовПлан,
    подходовЗакрыто: подходовЗакрыто, деньЗакрыт: деньЗакрыт,
    серия: серия, доСерии: доСерии,
    серияПодУгрозой: серияПодУгрозой, серияВозможна: серияВозможна,
    разгрузкаЕсть: разгрузкаЕсть, разгрузкаЧерез: разгрузкаЧерез,
    разгрузкаНеделя: разгрузкаНеделя, наРазгрузке: наРазгрузке
  };
}

/* Разметка карточки. Строка — «подпись слева, число справа»: так её читают
   одним взглядом сверху вниз, а не разбирают предложение. */
function segodnyaHtml(ds) {
  const s = segodnyaSvodka(ds);
  if (!s) return '';

  const дня = n => plural(n, 'день', 'дня', 'дней');
  const нед = n => plural(n, 'неделя', 'недели', 'недель');
  const недЧерез = n => plural(n, 'неделю', 'недели', 'недель');
  const ряд = (метка, знач, доп, кл) =>
    '<div class="sgd-r"><span>' + esc(метка) + '</span>' +
    '<b' + (кл ? ' class="' + кл + '"' : '') + '>' + знач +
    (доп ? '<em>' + доп + '</em>' : '') + '</b></div>';

  const тон = { 'ждём': 'wait', 'засчитана': 'ok', 'срыв': 'bad', 'успеваем': 'go' }[s.вердикт];
  const шапкаСправа = s.ждём ? 'ожидание'
    : 'неделя ' + s.неделя + ' · цикл ' + s.циклН + '/' + s.циклВсего;

  const ряды = [];

  if (!s.ждём) {
    ряды.push(ряд('Зачёт', esc(s.закрыто + ' / ' + s.норма), esc('из 4'),
      s.осталось === 0 ? 'sgd-up' : (s.успеваем ? '' : 'sgd-dn')));
    ряды.push(ряд('Впереди', esc(s.днейВпереди + ' ' + дня(s.днейВпереди)),
      esc('можно закрыть ' + s.доступно), s.успеваем ? '' : 'sgd-dn'));
  }

  // Сегодня. В день отдыха про подходы не говорим вовсе: «осталось закрыть»
  // там означало бы долг, которого программа не ставила.
  if (s.отдых) {
    ряды.push(ряд('Сегодня', esc('Отдых'), esc(s.деньИмя || ''), 'sgd-mut'));
  } else {
    ряды.push(ряд('Сегодня', esc(s.деньПодпись || s.деньИмя || 'Тренировка'),
      esc(s.упражнений + ' ' + plural(s.упражнений, 'упражнение', 'упражнения', 'упражнений')),
      s.деньЗакрыт ? 'sgd-up' : ''));
    ряды.push(ряд('Подходы', esc(s.подходовЗакрыто + ' из ' + s.подходовПлан),
      esc(s.деньЗакрыт ? 'день закрыт' : 'день открыт'),
      s.деньЗакрыт ? 'sgd-up' : ''));
  }

  ряды.push(ряд('Серия', esc(s.серия + ' ' + нед(s.серия)),
    s.серияПодУгрозой
      ? esc(s.серияВозможна ? 'оборвётся без ещё ' + s.доСерии : 'в эту неделю уже не спасти')
      : (s.серия > 0 ? esc('по четыре подряд') : esc('пока пусто')),
    s.серияПодУгрозой ? 'sgd-dn' : (s.серия > 0 ? 'sgd-up' : 'sgd-mut')));

  if (!s.ждём && s.разгрузкаЕсть) {
    ряды.push(ряд('Разгрузка',
      s.наРазгрузке ? esc('на этой неделе')
        : esc('через ' + s.разгрузкаЧерез + ' ' + недЧерез(s.разгрузкаЧерез)),
      esc('неделя ' + s.разгрузкаНеделя + ' цикла'),
      s.наРазгрузке ? 'sgd-wr' : ''));
  }

  const доля = s.норма > 0 ? Math.max(0, Math.min(100, Math.round(s.закрыто / s.норма * 100))) : 0;
  const полоска = s.ждём ? ''
    : '<div class="sgd-bar' + (s.успеваем ? '' : ' bad') + '"><i style="width:' + доля + '%"></i></div>';

  return '<div class="win sgd">' +
    '<div class="sgd-h"><b>Что сегодня</b><i>' + esc(шапкаСправа) + '</i></div>' +
    '<div class="sgd-v ' + тон + '"><div class="sgd-vt">' + esc(s.вердиктТекст) + '</div>' +
    '<div class="sgd-vd">' + esc(s.вердиктПодпись) + '</div></div>' +
    полоска +
    '<div class="sgd-l">' + ряды.join('') + '</div>' +
    '</div>';
}

/* То, что лежит в реестре. Отдельной функцией, чтобы повторная
   регистрация не поставила карточку дважды. */
function segodnyaCard() { return segodnyaHtml(today()); }

if (typeof HOOK === 'object' && HOOK && Array.isArray(HOOK.prog) &&
    HOOK.prog.indexOf(segodnyaCard) < 0) HOOK.prog.push(segodnyaCard);
